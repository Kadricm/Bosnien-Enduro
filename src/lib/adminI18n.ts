// Admin panel texts: bs (default), de, en. Language chosen via ?alang= and remembered in a cookie.
import type { AstroCookies } from 'astro';

export type AdminLang = 'bs' | 'de' | 'en';
export const ADMIN_LANGS: AdminLang[] = ['bs', 'de', 'en'];
const COOKIE = 'be_admin_lang';

export function adminLang(url: URL, cookies: AstroCookies): AdminLang {
  const q = url.searchParams.get('alang') as AdminLang | null;
  if (q && ADMIN_LANGS.includes(q)) {
    cookies.set(COOKIE, q, { path: '/', sameSite: 'lax', maxAge: 365 * 86400 });
    return q;
  }
  const c = cookies.get(COOKIE)?.value as AdminLang | undefined;
  return c && ADMIN_LANGS.includes(c) ? c : 'bs';
}

